// AutoFaber reads Vigil's live board, keeps watch, and checks it in the system check.
import assert from "node:assert/strict";
import { upstream } from "../vg/mocks.mjs";
globalThis.fetch = async (u, o) => upstream(typeof u === "string" ? u : u.url, o);
const H = await import("./harness.mjs"); const { call, calls, db } = H;
const M = "workers-ai|@cf/openai/gpt-oss-120b";
const ok = (m) => console.log("  ✓ " + m);
await call("/chat", { model: M, cid: "v", messages: [{ role: "user", text: "any planes squawking emergency right now?" }] });
let sys = calls.at(-1).sys;
assert.match(sys, /VIGIL LIVE BOARD/); assert.match(sys, /AIR TRAFFIC: Worldwide: 8,\d{3} aircraft/); assert.match(sys, /TAM3054 \(A320\) squawk 7700/);
assert.doesNotMatch(sys, /EARTHQUAKES:/); ok("an air question gets the air board only");
await call("/chat", { model: M, cid: "v", messages: [{ role: "user", text: "brief me on the situation" }] });
sys = calls.at(-1).sys;
for (const k of ["AIR TRAFFIC", "EARTHQUAKES", "SPACE WEATHER", "CONFLICT", "LAUNCHES", "ISS", "MARKETS"]) assert.match(sys, new RegExp(k + ": "), k);
assert.match(sys, /M6\.1 120 km S of Somewhere/); assert.match(sys, /Solar wind \d+ km\/s/); ok("a briefing reads every topic");
await call("/chat", { model: M, cid: "v", vigil: { where: { lat: 39.2, lon: -85.9, name: "Columbus, IN" }, view: "air", sel: "UAL2677 B739 FL340" }, messages: [{ role: "user", text: "what is that one?" }] });
sys = calls.at(-1).sys;
assert.match(sys, /his position: Columbus, IN/); assert.match(sys, /Within 60 nm of Columbus, IN: \d+ aircraft/); assert.match(sys, /selected: UAL2677/); ok("from inside Vigil: the board, his position and his selection ride along");
await call("/chat", { model: M, cid: "w", messages: [{ role: "user", text: "write me a haiku" }] });
assert.doesNotMatch(calls.at(-1).sys, /VIGIL LIVE BOARD/); ok("unrelated chats don't carry the board");
await call("/chat", { model: M, cid: "x", messages: [{ role: "user", text: "any planes overhead?" }] }, false);
assert.doesNotMatch(calls.at(-1).sys, /VIGIL LIVE BOARD/); ok("visitors never get it");
let r = await call("/genesis/watch", { home: { lat: 39.2, lon: -85.9, name: "Columbus" } });
assert.ok(r.noted >= 1, JSON.stringify(r));
const j = db.prepare("SELECT text FROM journal WHERE kind='watch'").all();
assert.equal(j.length, 1); assert.match(j[0].text, /TAM3054.*7700/); ok("watch notes the emergency squawk once: " + j[0].text.slice(0, 90));
r = await call("/genesis/watch", {}); assert.equal(r.noted, 0); assert.equal(db.prepare("SELECT COUNT(*) c FROM journal WHERE kind='watch'").get().c, 1); ok("…and not again");
await call("/chat", { model: M, cid: "y", messages: [{ role: "user", text: "hey" }] });
assert.match(calls.at(-1).sys, /What you noticed on Vigil's live board lately[^\n]*TAM3054/); ok("AutoFaber knows what it noticed");
r = await call("/genesis/health"); const v = r.checks.find((c) => c.name === "Vigil live board"); assert.ok(v && v.ok, JSON.stringify(v)); ok("system check: " + v.detail);
r = await call("/genesis"); assert.ok(r.watch.length === 1); ok("panel data carries the watch notes");
console.log("all passed");
